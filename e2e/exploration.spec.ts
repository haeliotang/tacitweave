test('a saved space can branch and compare its explicit configuration', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Explore$/ }).click()
  await page.getByRole('button', { name: 'Start blank' }).click()
  await page.locator('.object-palette').getByRole('button', { name: 'Door' }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const object = page.locator('.spatial-object.kind-door')
  const box = await object.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2 + 80, box!.y + box!.height / 2, { steps: 4 })
  await page.mouse.up()
  await page.getByRole('button', { name: 'Save as new branch' }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: /Explore$/ }).click()
  await expect(page.locator('.saved-trail').first()).toContainText('2 versions')
  await expect(page.locator('.saved-space-row')).toHaveCount(2)
  const parentRow = page.locator('.saved-space-row').first()
  await parentRow.getByRole('button', { name: 'Delete space' }).click()
  await parentRow.getByRole('button', { name: 'Confirm delete space' }).click()
  await expect(page.getByRole('alert')).toContainText('child versions')
  await expect(page.locator('.saved-space-row')).toHaveCount(2)
  await page.locator('.space-compare summary').click()
  const selects = page.locator('.space-compare select')
  await selects.nth(0).selectOption({ index: 1 })
  await selects.nth(1).selectOption({ index: 2 })
  await expect(page.locator('.space-diff')).toContainText('position')
  await page.getByRole('button', { name: 'Overlay comparison' }).click()
  await expect(page.locator('.space-overlay')).toBeVisible()
  await expect(page.locator('.space-overlay .overlay-object')).toHaveCount(2)
})



import { expect, test } from '@playwright/test'

test('a user can shape a space before entering it', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Load demo field' }).click()
  await page.locator('.recent-item').first().click()
  await page.getByRole('button', { name: 'Open fragment details' }).click()
  await page.getByRole('button', { name: 'Customize space' }).click()
  const composer = page.locator('.space-composer')
  await expect(composer).toBeVisible()
  await composer.getByRole('button', { name: 'Corridor' }).click()
  await composer.getByRole('button', { name: 'Door' }).click()
  await composer.locator('select').last().selectOption('180')
  await composer.getByRole('button', { name: 'Enter this space' }).click()
  await expect(page.locator('.symbolic-episode')).toBeVisible()
  await expect(page.getByText('This space')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Stay 30 more seconds' })).toBeVisible()
  await page.locator('.symbolic-motif-change select').selectOption('water')
  await page.locator('.symbolic-light-change select').selectOption('low')
  await expect(page.locator('.symbolic-episode')).toHaveClass(/light-low/)
  await expect(page.locator('.symbolic-episode')).toHaveClass(/motif-water/)
  const figure = page.locator('.symbolic-figure')
  await page.locator('.symbolic-figure-change select').selectOption('none')
  await expect.poll(async () => figure.evaluate(element => getComputedStyle(element).opacity)).toBe('0')
  await page.locator('.symbolic-figure-change select').selectOption('animal')
  await expect(figure).toHaveClass(/figure-animal/)
  await expect.poll(async () => figure.evaluate(element => getComputedStyle(element).opacity)).toBe('1')
  await page.getByRole('button', { name: 'Save as a new visit' }).click()
  await expect(page.getByRole('heading', { name: 'Past fragments can be re-entered' })).toBeVisible()
  await expect(page.locator('.continuity-visit')).toHaveCount(2)
  await expect(page.getByText('Space configuration')).toBeVisible()
  await expect(page.getByText(/1 sessions/)).toBeVisible()
  await page.getByRole('button', { name: 'Enter latest space' }).click()
  await expect(page.locator('.symbolic-episode')).toHaveClass(/motif-water/)
  await expect(page.locator('.symbolic-figure')).toHaveClass(/figure-animal/)
  await expect.poll(async () => page.locator('.symbolic-figure').evaluate(element => getComputedStyle(element).opacity)).toBe('1')
})


test('an open-ended space has no automatic end or extension button', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Load demo field' }).click()
  await page.locator('.recent-item').first().click()
  await page.getByRole('button', { name: 'Open fragment details' }).click()
  await page.getByRole('button', { name: 'Customize space' }).click()
  const composer = page.locator('.space-composer')
  await composer.locator('select').last().selectOption('open')
  await composer.getByRole('button', { name: 'Enter this space' }).click()
  await expect(page.locator('.symbolic-episode')).toBeVisible()
  await expect(page.locator('.symbolic-progress')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Stay 30 more seconds' })).toHaveCount(0)
})
